"""
schema.py -- Target Schema & Column Classification for Anvaya Enrichment Pipeline

WHAT: Defines every column in the expected output delivery format and
      categorizes it by how the pipeline should populate it.

WHY:  This is the single source of truth for "what does the pipeline
      need to produce?". Every module checks here to know which columns
      it owns, and evaluation checks here to know what to score.

HOW:  Each column is assigned to exactly one category:

      PASSTHROUGH  - Copied from raw input unchanged.
      CLEAN        - Copied from raw input, then cleaned (placeholder
                     removal, whitespace trimming, etc.).
      DETERMINISTIC - Generated by rule-based logic from raw columns
                     (string parsing, formatting templates). No AI needed.
      AI_ENRICHMENT - Requires semantic understanding (NLP, embeddings,
                     LLM generation). Built in later phases.
      EXTERNAL_DATA - Cannot be derived from the 6 raw columns at all.
                     Requires external reference files, web lookups,
                     or manual entry.

NOTE: Some columns are listed under DETERMINISTIC with a caveat that
      they produce partial/approximate output without external data.
      The pipeline should still attempt them, and flag low-confidence
      results for human review.
"""


