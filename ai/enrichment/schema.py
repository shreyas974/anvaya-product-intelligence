def all_enrichment_columns() -> list[str]:
    """All columns the pipeline is responsible for generating (not passthrough)."""
    return CLEAN_COLUMNS + DETERMINISTIC_COLUMNS + AI_ENRICHMENT_COLUMNS + EXTERNAL_DATA_COLUMNS


def columns_for_phase(phase: int) -> list[str]:
    """
    Return the columns that should be populated by a given pipeline phase.

    Phase 1 (deterministic): PASSTHROUGH + CLEAN + DETERMINISTIC
    Phase 2 (AI):            AI_ENRICHMENT
    Phase 3 (external):      EXTERNAL_DATA (when reference files are added)
    """
    if phase == 1:
        return PASSTHROUGH_COLUMNS + CLEAN_COLUMNS + DETERMINISTIC_COLUMNS
    elif phase == 2:
        return AI_ENRICHMENT_COLUMNS
    elif phase == 3:
        return EXTERNAL_DATA_COLUMNS
    else:
        raise ValueError(f"Unknown phase: {phase}")


def validate_output_columns(columns: list[str]) -> dict:
    """
    Check a list of output columns against the expected schema.
    Returns dict with 'missing' and 'extra' lists.
    """
    expected = set(OUTPUT_COLUMN_ORDER)
    actual = set(columns)
    return {
        "missing": sorted(expected - actual),
        "extra": sorted(actual - expected),
    }
